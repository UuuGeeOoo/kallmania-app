const BRAND = "FF1F2937";   // slate-800
const ACCENT = "FFC2641F";  // brand orange
const LIGHT = "FFF3F4F6";
const GREEN = "FF15803D";
const RED = "FFB91C1C";
const AMBER = "FFB45309";

type Wb = ExcelJS.Workbook;
type Ws = ExcelJS.Worksheet;

function newWorkbook(title: string, subtitle: string, periodLabel: string, generatedBy: string): { wb: Wb; ws0: Ws } {
  const wb = new ExcelJS.Workbook();
  wb.creator = `${COMPANY_HEADER} — Kallmania Operational Intelligence`;
  wb.created = new Date();
  const ws0 = wb.addWorksheet("Cover", { views: [{ showGridLines: false }] });
  ws0.columns = [{ width: 34 }, { width: 60 }, { width: 30 }, { width: 30 }];
  ws0.addRow([COMPANY_HEADER]);
  ws0.getCell("A1").font = { bold: true, size: 20, color: { argb: ACCENT } };
  ws0.addRow([title]);
  ws0.getCell("A2").font = { bold: true, size: 14, color: { argb: BRAND } };
  ws0.addRow([subtitle]);
  ws0.getCell("A3").font = { size: 12, color: { argb: "FF6B7280" } };
  ws0.addRow([]);
  const meta: [string, string][] = [
    ["Reporting period", periodLabel],
    ["Report generated", new Date().toLocaleString("en-GB", { timeZone: "UTC" }) + " (UTC)"],
    ["Generated by", generatedBy],
    ["Data source", "Kallmania application records (reports, tasks, escalations, activity audit)"],
    ["Method", "KPI targets follow the roster method — per-agent daily target × agents working × report days"],
  ];
  for (const [k, v] of meta) {
    ws0.addRow([k, v]);
    ws0.getCell(`A${ws0.rowCount}`).font = { bold: true };
    ws0.getCell(`B${ws0.rowCount}`).font = { size: 10 };
  }
  ws0.addRow([]);
  ws0.addRow(["Note", "All figures are computed by application logic from existing records. Missing data is never treated as zero — unavailable metrics are marked 'Insufficient data'."]);
  ws0.getCell(`B${ws0.rowCount}`).font = { italic: true, size: 9, color: { argb: "FF6B7280" } };
  ws0.getCell(`B${ws0.rowCount}`).alignment = { wrapText: true };
  return { wb, ws0 };
}

function sheet(wb: Wb, name: string, opts?: { freeze?: boolean }): Ws {
  const ws = wb.addWorksheet(name.slice(0, 31), {
    views: [{ state: opts?.freeze === false ? "frozen" : "frozen", ySplit: 1, showGridLines: false }],
    pageSetup: { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0 },
  });
  return ws;
}

function section(ws: Ws, title: string, row: number): number {
  ws.mergeCells(`A${row}:H${row}`);
  const c = ws.getCell(`A${row}`);
  c.value = title;
  c.font = { bold: true, size: 12, color: { argb: BRAND } };
  c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: LIGHT } };
  return row + 1;
}

function kvTable(ws: Ws, rows: [string, unknown][], startRow: number, numFmt?: string): number {
  let r = startRow;
  for (const [k, v] of rows) {
    ws.getCell(`A${r}`).value = k;
    ws.getCell(`A${r}`).font = { bold: true, size: 10 };
    const cell = ws.getCell(`B${r}`);
    cell.value = (v === null || v === undefined || v === "") ? "—" : (v as ExcelJS.CellValue);
    if (typeof v === "number" && numFmt) cell.numFmt = numFmt;
    cell.font = { size: 10 };
    r++;
  }
  return r + 1;
}

function dataTable(ws: Ws, headers: string[], rows: (string | number | null | undefined)[][], startRow: number, opts?: { numFmts?: (string | undefined)[]; achievementCol?: number }): number {
  const headerRow = ws.getRow(startRow);
  headers.forEach((h, i) => {
    const c = headerRow.getCell(i + 1);
    c.value = h;
    c.font = { bold: true, size: 10, color: { argb: "FFFFFFFF" } };
    c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: BRAND } };
    c.alignment = { wrapText: true, vertical: "middle" };
    c.border = { bottom: { style: "thin" } };
  });
  headerRow.height = 22;
  let r = startRow + 1;
  for (const row of rows) {
    row.forEach((v, i) => {
      const c = ws.getCell(r, i + 1);
      c.value = (v === null || v === undefined) ? "—" : v;
      c.font = { size: 10 };
      if (typeof v === "number") {
        c.numFmt = opts?.numFmts?.[i] ?? "#,##0.##";
        c.alignment = { horizontal: "right" };
      }
    });
    r++;
  }
  if (rows.length > 0) {
    ws.autoFilter = {
      from: { row: startRow, column: 1 },
      to: { row: startRow + rows.length, column: headers.length },
    };
  }
  // Conditional formatting on an achievement-% column
  if (opts?.achievementCol) {
    const col = opts.achievementCol;
    const ref = `${ws.getCell(startRow + 1, col).address}:${ws.getCell(startRow + rows.length, col).address}`;
    ws.addConditionalFormatting({
      ref,
      rules: [
        { type: "cellIs", operator: "greaterThan", formulae: ["99.999"], priority: 1, style: { font: { color: { argb: GREEN }, bold: true } } },
        { type: "cellIs", operator: "between", formulae: ["80", "99.999"], priority: 2, style: { font: { color: { argb: AMBER } } } },
        { type: "cellIs", operator: "lessThan", formulae: ["80"], priority: 3, style: { font: { color: { argb: RED }, bold: true } } },
      ],
    });
  }
  return r + 1;
}

function autoWidth(ws: Ws, max = 46) {
  ws.columns.forEach((col) => {
    let w = 10;
    col.eachCell?.({ includeEmpty: false }, (cell) => {
      const len = String(cell.value ?? "").length + 2;
      if (len > w) w = Math.min(max, len);
    });
    col.width = w;
  });
}

function findingsBlock(ws: Ws, label: string, items: IntelFinding[], row: number): number {
  let r = section(ws, label, row);
  if (!items.length) {
    ws.getCell(`A${r}`).value = "None identified from the recorded evidence.";
    ws.getCell(`A${r}`).font = { italic: true, size: 10 };
    return r + 2;
  }
  for (const f of items) {
    ws.getCell(`A${r}`).value = f.title;
    ws.getCell(`A${r}`).font = { bold: true, size: 10 };
    ws.mergeCells(`B${r}:H${r}`);
    const c = ws.getCell(`B${r}`);
    c.value = f.evidence;
    c.font = { size: 10 };
    c.alignment = { wrapText: true };
    ws.getRow(r).height = 26;
    r++;
  }
  return r + 1;
}

function commentaryBlock(ws: Ws, title: string, commentary: { source: string; engineNote?: string; summary: string; strengths: string[]; weaknesses: string[]; risks: string[]; recommendations: string[] }, row: number): number {
  let r = section(ws, title, row);
  ws.getCell(`A${r}`).value = "Generated by";
  ws.getCell(`A${r}`).font = { bold: true, size: 10 };
  ws.getCell(`B${r}`).value = commentary.source === "gemini" ? "Google Gemini (AI interpretation — separate from the objective measurements above)" : commentary.source === "rule-based" ? "Application rule engine (evidence-based)" : "Unavailable";
  ws.getCell(`B${r}`).font = { size: 10 };
  r++;
  if (commentary.engineNote) {
    ws.mergeCells(`A${r}:H${r}`);
    ws.getCell(`A${r}`).value = commentary.engineNote;
    ws.getCell(`A${r}`).font = { italic: true, size: 9, color: { argb: AMBER } };
    r++;
  }
  const bullets = (label: string, arr: string[]) => {
    ws.getCell(`A${r}`).value = label;
    ws.getCell(`A${r}`).font = { bold: true, size: 10 };
    r++;
    for (const s of arr.slice(0, 8)) {
      ws.mergeCells(`B${r}:H${r}`);
      ws.getCell(`B${r}`).value = `• ${s}`;
      ws.getCell(`B${r}`).font = { size: 10 };
      ws.getCell(`B${r}`).alignment = { wrapText: true };
      ws.getRow(r).height = 24;
      r++;
    }
    r++;
  };
  ws.mergeCells(`B${r}:H${r}`);
  ws.getCell(`B${r}`).value = commentary.summary;
  ws.getCell(`B${r}`).font = { size: 10 };
  ws.getCell(`B${r}`).alignment = { wrapText: true };
  ws.getRow(r).height = 30;
  r += 2;
  bullets("Strengths (recommendations & interpretations — not established facts)", commentary.strengths);
  bullets("Weaknesses", commentary.weaknesses);
  bullets("Risks", commentary.risks);
  bullets("Recommendations", commentary.recommendations);
  return r;
}

function notesBlock(ws: Ws, notes: DataAvailabilityNote[], row: number): number {
  let r = section(ws, "Unavailable data & method notes", row);
  for (const n of notes) {
    ws.getCell(`A${r}`).value = n.metric;
    ws.getCell(`A${r}`).font = { bold: true, size: 10 };
    ws.mergeCells(`B${r}:H${r}`);
    ws.getCell(`B${r}`).value = n.note;
    ws.getCell(`B${r}`).font = { size: 10, italic: true };
    ws.getCell(`B${r}`).alignment = { wrapText: true };
    ws.getRow(r).height = 24;
    r++;
  }
  return r + 1;
}

