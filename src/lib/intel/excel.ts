// ─────────────────────────────────────────────────────────────────────────────
// PROFESSIONAL EXCEL EXPORTS (.xlsx) — the primary management export.
// Structured multi-sheet workbooks (never a flat table dump): corporate
// styling, report/period/generator headers, frozen header rows, auto-filtered
// data tables, number/percentage formatting, conditional formatting on KPI
// achievement, and an explicit unavailable-data note on every workbook.
// Editable after download (no protection applied).
