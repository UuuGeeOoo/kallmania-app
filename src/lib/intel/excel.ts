// ── Individual agent workbook ──
export async function agentWorkbook(report: Exclude<AgentReport, { error: string }>, generatedBy: string): Promise<ExcelJS.Buffer> {
  const { wb } = newWorkbook("Individual Agent Operational Report", report.profile.fullName, report.period.label, generatedBy);

  // Executive Summary
  let ws = sheet(wb, "Executive Summary");
  ws.columns = [{ width: 36 }, { width: 46 }, { width: 18 }, { width: 18 }, { width: 16 }, { width: 16 }, { width: 16 }, { width: 16 }];
  let r = section(ws, "Executive Summary", 1);
  const a = report.assessment;
  r = kvTable(ws, [
    ["Agent", report.profile.fullName],
    ["Team", report.profile.teamLabel ?? "—"],
    ["Centre", report.profile.centre],
    ["Reporting period", report.period.label],
    ["Overall classification", CLASSIFICATION_LABELS[a.classification] ?? a.classification],
    ["Overall score (0–100)", a.score ?? "Insufficient data"],
    ["Score coverage", a.coverageNote ?? "All components had data"],
    ["Mean KPI achievement", report.kpi.summary.meanAchPct !== null ? `${report.kpi.summary.meanAchPct}%` : "Insufficient data"],
    ["KPI status counts", `Exceeded ${report.kpi.summary.exceeded} · Met ${report.kpi.summary.met} · Approaching ${report.kpi.summary.approaching} · Below ${report.kpi.summary.below} · Critical ${report.kpi.summary.critical}`],
    ["Tasks completed / assigned", `${report.tasks.completed} / ${report.tasks.assigned} (${report.tasks.completionRatePct ?? "—"}%)`],
    ["Reporting compliance", report.attendance.available || report.profile.daysWithRecordedActivity ? `${new Set(report.kpi.submittedDates).size} submitted day(s)` : "—"],
    ["AI engine", a.commentary.source === "gemini" ? "Google Gemini" : "Rule-based (verified figures only)"],
  ], r);
  r = commentaryBlock(ws, "Management assessment", a.commentary, r);
  r = notesBlock(ws, report.dataNotes, r);
  autoWidth(ws);

  // Agent Profile
  ws = sheet(wb, "Agent Profile");
  ws.columns = [{ width: 34 }, { width: 50 }];
  r = section(ws, "Agent Profile & Employment Information", 1);
  r = kvTable(ws, Object.entries(report.profile).map(([k, v]) => [k.replace(/([A-Z])/g, " $1").replace(/^./, (c) => c.toUpperCase()), typeof v === "string" ? v : v === null ? "—" : String(v)] as [string, string]), r);
  autoWidth(ws);

  // KPI Breakdown
  ws = sheet(wb, "KPI Breakdown");
  ws.columns = [{ width: 30 }, { width: 26 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 16 }, { width: 22 }, { width: 14 }, { width: 30 }];
  r = section(ws, "KPI Performance Analysis (achievement % = direction-aware; lower-is-better metrics invert)", 1);
  r = dataTable(ws,
    ["KPI", "Unit", "Target (period)", "Actual", "Variance", "Achievement %", "Status", "Trend vs prev", "Notes"],
    report.kpi.rows.map((row) => [
      row.label, row.unit, row.target, row.actual, row.variance, row.achievementPct,
      KPI_STATUS_LABELS[row.status] ?? row.status,
      row.trend === "no_history" ? "—" : row.trend + (row.trendDeltaPct !== null ? ` (${row.trendDeltaPct > 0 ? "+" : ""}${row.trendDeltaPct} pts)` : ""),
      row.notes ?? "",
    ]),
    r, { achievementCol: 6 },
  );
  r = section(ws, "Best & weakest KPI identification", r);
  const bw = report.bestWeakest;
  r = kvTable(ws, [
    ["Strongest KPI", bw.strongest ? `${bw.strongest.label} — ${bw.strongest.why}` : "Insufficient data"],
    ["Weakest KPI", bw.weakest ? `${bw.weakest.label} — ${bw.weakest.why}` : "Insufficient data"],
    ["Largest negative variance", bw.largestNegativeVariance ? `${bw.largestNegativeVariance.label} (${bw.largestNegativeVariance.variance})` : "None negative"],
    ["Greatest improvement", bw.greatestImprovement ? `${bw.greatestImprovement.label} (${bw.greatestImprovement.deltaPct} pts vs previous period)` : "No comparable history"],
    ["Greatest decline", bw.greatestDecline ? `${bw.greatestDecline.label} (${bw.greatestDecline.deltaPct} pts vs previous period)` : "No decline recorded"],
    ["Most consistent", bw.mostConsistent ? bw.mostConsistent.label : "Insufficient historical data"],
    ["Requiring attention", bw.requiringAttention.length ? bw.requiringAttention.map((x) => `${x.label} (${KPI_STATUS_LABELS[x.status]})`).join("; ") : "None"],
  ], r);
  autoWidth(ws);

  // Application Activity
  ws = sheet(wb, "Application Activity");
  ws.columns = [{ width: 36 }, { width: 30 }, { width: 26 }, { width: 26 }];
  r = section(ws, "Application Usage & Activity Analysis", 1);
  r = kvTable(ws, [
    ["Successful logins", report.activity.successfulLogins],
    ["Previous-period logins", report.activity.prevLogins],
    ["Last login", report.activity.lastLoginAt ? new Date(report.activity.lastLoginAt).toLocaleString("en-GB") : "No login recorded"],
    ["First recorded activity", report.activity.firstRecordedActivity ? new Date(report.activity.firstRecordedActivity).toLocaleString("en-GB") : "—"],
    ["Most recent activity", report.activity.mostRecentActivity ? new Date(report.activity.mostRecentActivity).toLocaleString("en-GB") : "—"],
    ["Active days (any activity)", report.activity.activeDays],
    ["Days with meaningful work activity", report.activity.meaningfulWorkDays],
    ["Reports created", report.activity.reportsCreated],
    ["Reports submitted", report.activity.reportsSubmitted],
    ["Reports returned / rejected", report.activity.reportsRejected],
    ["Drafts saved", report.activity.draftsSaved],
    ["Task status updates", report.activity.taskStatusUpdates],
    ["Tasks completed (events)", report.activity.tasksCompletedEvents],
    ["Escalations raised", report.activity.escalationsRaised],
    ["Escalation replies", report.activity.escalationReplies],
    ["Announcements acknowledged", "Not currently tracked by the application."],
  ], r);
  ws.getCell(`A${r}`).value = "Note: a login is authentication, not productivity — meaningful work activity is measured separately above.";
  ws.getCell(`A${r}`).font = { italic: true, size: 9, color: { argb: "FF6B7280" } };
  autoWidth(ws);

  // Task Performance
  ws = sheet(wb, "Task Performance");
  ws.columns = [{ width: 36 }, { width: 24 }, { width: 24 }];
  r = section(ws, "Task Management & Completion Analysis", 1);
  const t = report.tasks;
  r = kvTable(ws, [
    ["Tasks assigned", t.assigned],
    ["Completed", t.completed],
    ["Pending (open)", t.pending],
    ["Overdue", t.overdue],
    ["Blocked", t.blocked],
    ["Not completed (distinguished from completed)", t.cancelledOrNotCompleted],
    ["Completed before deadline", t.completedBeforeDeadline],
    ["Completed after deadline", t.completedAfterDeadline],
    ["Completion rate %", t.completionRatePct],
    ["Punctuality % (on-time / deadline-bearing)", t.punctualityPct],
    ["Average completion time (hours)", t.avgCompletionHours],
    ["Previous period: completed", t.prev.completed],
    ["Previous period: overdue", t.prev.overdue],
  ], r, "#,##0.##");
  r = notesBlock(ws, [{ metric: "Completion timestamps", note: "Task completion time uses the task's last update as the completion proxy — the application does not keep a distinct completion event for every path." }], r);
  autoWidth(ws);

  // Attendance & Compliance
  ws = sheet(wb, "Attendance & Compliance");
  ws.columns = [{ width: 40 }, { width: 30 }];
  r = section(ws, "Attendance, Punctuality & Reporting Compliance", 1);
  const at = report.attendance;
  r = kvTable(ws, [
    ["Attendance data available", at.available ? "Yes" : "No reliable records in the period"],
    ["Scheduled working days", at.scheduledDays],
    ["Days with an attendance record", at.daysWithRecord],
    ["Present", at.present],
    ["Late arrivals", at.late],
    ["Reported absent (own report)", at.absent],
    ["Scheduled days without a record", at.missingRecords],
    ["Attendance % (of RECORDED days)", at.attendancePct],
    ["Punctuality % (present / recorded)", at.punctualityPct],
    ["Average lateness (mins)", at.avgLatenessMins],
  ], r);
  ws.getCell(`A${r}`).value = "A missing attendance record is NEVER counted as an absence — attendance is only recorded via the daily report attendance block.";
  ws.getCell(`A${r}`).font = { italic: true, size: 9, color: { argb: "FF6B7280" } };
  autoWidth(ws);

  // Strengths & Weaknesses
  ws = sheet(wb, "Strengths & Weaknesses");
  ws.columns = [{ width: 36 }, { width: 70 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 }];
  r = section(ws, "Evidence-Based Strengths & Weaknesses", 1);
  r = findingsBlock(ws, "Strengths (measured)", report.strengths, r);
  r = findingsBlock(ws, "Weaknesses (measured)", report.weaknesses, r);
  r = findingsBlock(ws, "Performance risks", report.risks, r);
  r = section(ws, "Overall score components (transparent weighting)", r);
  r = dataTable(ws, ["Component", "Weight", "Earned", "Included", "Basis"],
    a.scoreComponents.map((c) => [c.label, c.weight, c.earned, c.included ? "Yes" : "No (no data)", c.basis]),
    r);
  autoWidth(ws);

  // Recommendations
  ws = sheet(wb, "Recommendations");
  ws.columns = [{ width: 36 }, { width: 70 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 }];
  r = commentaryBlock(ws, "Recommendations & coaching", a.commentary, 1);
  r = notesBlock(ws, report.dataNotes, r);
  autoWidth(ws);

  // Historical Trends
  ws = sheet(wb, "Historical Trends");
  ws.columns = [{ width: 14 }, { width: 22 }, { width: 22 }, { width: 22 }];
  r = section(ws, "Submitted reports per week (period buckets)", 1);
  r = dataTable(ws, ["Week", "Reports submitted", "Tasks completed (events)"], report.activity.activityTrend.map((p) => [p.label, p.submitted, p.tasksCompleted]), r);
  if (report.kpi.rows.every((x) => x.trendDeltaPct === null)) {
    ws.getCell(`A${r}`).value = "Insufficient historical data to establish a reliable performance trend.";
    ws.getCell(`A${r}`).font = { italic: true, size: 10 };
  }
  autoWidth(ws);

  return wb.xlsx.writeBuffer();
}

